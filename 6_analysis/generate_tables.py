#!/usr/bin/env python3
"""Generate LaTeX tables for MX unified coprocessor fault analysis paper.

Reads CSV results and produces standalone LaTeX table files suitable for
\\input{} inclusion in a paper. All tables use booktabs formatting.

Tables generated:
  1. vulnerability_ranking.tex — 5-way format ranking
  2. per_matrix_breakdown.tex — misclass per weight matrix
  3. bit_sensitivity.tex — bit-position sensitivity
  4. cycle_comparison.tex — SW vs HW coprocessor cycles
  5. resource_utilization.tex — FPGA resource usage
  6. instruction_encoding.tex — MX instruction format table

Usage:
  python3 generate_tables.py results/
  python3 generate_tables.py results/ --output tables/

Authors: Dillibabu Shanmugam, Patrick Schaumont (WPI)
"""

import argparse
import csv
import os
import sys
from collections import defaultdict

# ─────────────────────────────────────────────────────────────────────
# Configuration
# ─────────────────────────────────────────────────────────────────────

FORMATS = ["mxint8", "mxfp8_e4m3", "mxfp8_e5m2", "mxlog8", "mxlog8_logdom"]

FORMAT_LABELS = {
    "mxint8":        "MXINT8",
    "mxfp8_e4m3":   "MXFP8-E4M3",
    "mxfp8_e5m2":   "MXFP8-E5M2",
    "mxlog8":        "MXLOG8",
    "mxlog8_logdom": "MXLOG8-Logdom",
}

MATRICES = ["W_Q", "W_K", "W_V", "W_L1", "W_L2"]

# Software cycle counts from CAPRI1 attention benchmarks
SW_CYCLES = {
    "mxint8":        9010,
    "mxfp8_e4m3":   10233,
    "mxfp8_e5m2":   10111,
    "mxlog8":        9382,
    "mxlog8_logdom": 8822,
}

# Estimated coprocessor cycle counts
HW_CYCLES_EST = {
    "mxint8":        1800,
    "mxfp8_e4m3":   2000,
    "mxfp8_e5m2":   2000,
    "mxlog8":        1700,
    "mxlog8_logdom": 1500,
}

# Binary sizes (bytes)
BINARY_SIZES = {
    "mxint8":        784,
    "mxfp8_e4m3":   820,
    "mxfp8_e5m2":   820,
    "mxlog8":        840,
    "mxlog8_logdom": 896,
}


# ─────────────────────────────────────────────────────────────────────
# Data loading
# ─────────────────────────────────────────────────────────────────────

def load_results(results_dir):
    """Load all sram_faults_*.csv files."""
    all_data = {}
    for fmt in FORMATS:
        csv_path = os.path.join(results_dir, f"sram_faults_{fmt}.csv")
        if not os.path.exists(csv_path):
            continue
        with open(csv_path, "r") as f:
            all_data[fmt] = list(csv.DictReader(f))
    return all_data


# ─────────────────────────────────────────────────────────────────────
# Table 1: Vulnerability Ranking
# ─────────────────────────────────────────────────────────────────────

def gen_vulnerability_ranking(all_data, output_dir):
    """Generate 5-way vulnerability ranking table."""
    rows = []
    for fmt, data in all_data.items():
        total = len(data)
        misclass = sum(1 for r in data if r["outcome"] == "misclass")
        crash = sum(1 for r in data if r["outcome"] == "crash")
        normal = total - misclass - crash
        vuln_pct = 100.0 * misclass / max(1, total)
        rows.append((fmt, total, misclass, crash, normal, vuln_pct))

    # Sort by vuln_pct ascending (most resilient first)
    rows.sort(key=lambda x: x[5])

    tex = []
    tex.append(r"% Auto-generated by generate_tables.py")
    tex.append(r"\begin{table}[t]")
    tex.append(r"\centering")
    tex.append(r"\caption{5-Way SRAM Fault Vulnerability Ranking — "
               r"Unified MX Coprocessor}")
    tex.append(r"\label{tab:vuln-ranking}")
    tex.append(r"\begin{tabular}{clrrrr}")
    tex.append(r"\toprule")
    tex.append(r"\textbf{Rank} & \textbf{Format} & \textbf{Total} & "
               r"\textbf{Misclass} & \textbf{Crash} & \textbf{Vuln\%} \\")
    tex.append(r"\midrule")

    for rank, (fmt, total, misclass, crash, normal, vuln_pct) in enumerate(rows, 1):
        label = FORMAT_LABELS.get(fmt, fmt)
        # Bold the best and worst
        if rank == 1:
            pct_str = r"\textbf{" + f"{vuln_pct:.1f}" + r"\%}"
        elif rank == len(rows):
            pct_str = r"\textbf{" + f"{vuln_pct:.1f}" + r"\%}"
        else:
            pct_str = f"{vuln_pct:.1f}\\%"
        tex.append(f"  {rank} & {label} & {total:,} & {misclass:,} & "
                   f"{crash:,} & {pct_str} \\\\")

    tex.append(r"\bottomrule")
    tex.append(r"\end{tabular}")
    tex.append(r"\end{table}")

    path = os.path.join(output_dir, "vulnerability_ranking.tex")
    with open(path, "w") as f:
        f.write("\n".join(tex) + "\n")
    print(f"  Saved {path}")


# ─────────────────────────────────────────────────────────────────────
# Table 2: Per-Matrix Breakdown
# ─────────────────────────────────────────────────────────────────────

def gen_per_matrix_breakdown(all_data, output_dir):
    """Generate per-matrix misclass breakdown table."""
    tex = []
    tex.append(r"% Auto-generated by generate_tables.py")
    tex.append(r"\begin{table}[t]")
    tex.append(r"\centering")
    tex.append(r"\caption{Per-Matrix Misclassification Breakdown}")
    tex.append(r"\label{tab:per-matrix}")

    n_cols = len(MATRICES)
    col_spec = "l" + "r" * n_cols + "r"
    tex.append(r"\begin{tabular}{" + col_spec + "}")
    tex.append(r"\toprule")

    header = r"\textbf{Format}"
    for mat in MATRICES:
        header += f" & \\textbf{{{mat}}}"
    header += r" & \textbf{Total} \\"
    tex.append(header)
    tex.append(r"\midrule")

    for fmt in FORMATS:
        if fmt not in all_data:
            continue
        label = FORMAT_LABELS.get(fmt, fmt)
        rows = all_data[fmt]
        total_mc = 0
        cells = []
        for mat in MATRICES:
            mat_rows = [r for r in rows if r["matrix"] == mat]
            mc = sum(1 for r in mat_rows if r["outcome"] == "misclass")
            mt = len(mat_rows)
            total_mc += mc
            if mt > 0:
                pct = 100.0 * mc / mt
                if pct > 5:
                    cells.append(r"\textbf{" + f"{mc}/{mt}" + "}")
                else:
                    cells.append(f"{mc}/{mt}")
            else:
                cells.append("---")
        tex.append(f"  {label} & " + " & ".join(cells) + f" & {total_mc} \\\\")

    tex.append(r"\bottomrule")
    tex.append(r"\end{tabular}")
    tex.append(r"\end{table}")

    path = os.path.join(output_dir, "per_matrix_breakdown.tex")
    with open(path, "w") as f:
        f.write("\n".join(tex) + "\n")
    print(f"  Saved {path}")


# ─────────────────────────────────────────────────────────────────────
# Table 3: Bit Sensitivity
# ─────────────────────────────────────────────────────────────────────

def gen_bit_sensitivity(all_data, output_dir):
    """Generate bit-position sensitivity table."""
    tex = []
    tex.append(r"% Auto-generated by generate_tables.py")
    tex.append(r"\begin{table}[t]")
    tex.append(r"\centering")
    tex.append(r"\caption{Bit-Position Sensitivity — Misclassification Rate (\%)}")
    tex.append(r"\label{tab:bit-sensitivity}")
    tex.append(r"\begin{tabular}{l*{8}{r}}")
    tex.append(r"\toprule")
    tex.append(r"\textbf{Format} & \textbf{b0} & \textbf{b1} & \textbf{b2} & "
               r"\textbf{b3} & \textbf{b4} & \textbf{b5} & \textbf{b6} & "
               r"\textbf{b7} \\")
    tex.append(r"\midrule")

    for fmt in FORMATS:
        if fmt not in all_data:
            continue
        label = FORMAT_LABELS.get(fmt, fmt)
        rows = all_data[fmt]
        bit_counts = defaultdict(int)
        bit_totals = defaultdict(int)
        for r in rows:
            bit = int(r["bit_in_byte"])
            bit_totals[bit] += 1
            if r["outcome"] == "misclass":
                bit_counts[bit] += 1

        cells = []
        for b in range(8):
            total = bit_totals.get(b, 0)
            mc = bit_counts.get(b, 0)
            if total > 0:
                pct = 100.0 * mc / total
                if pct > 5:
                    cells.append(r"\textbf{" + f"{pct:.1f}" + "}")
                else:
                    cells.append(f"{pct:.1f}")
            else:
                cells.append("---")
        tex.append(f"  {label} & " + " & ".join(cells) + " \\\\")

    tex.append(r"\bottomrule")
    tex.append(r"\end{tabular}")
    tex.append(r"\end{table}")

    path = os.path.join(output_dir, "bit_sensitivity.tex")
    with open(path, "w") as f:
        f.write("\n".join(tex) + "\n")
    print(f"  Saved {path}")


# ─────────────────────────────────────────────────────────────────────
# Table 4: Cycle Comparison (SW vs HW)
# ─────────────────────────────────────────────────────────────────────

def gen_cycle_comparison(output_dir):
    """Generate SW vs HW coprocessor cycle comparison table."""
    tex = []
    tex.append(r"% Auto-generated by generate_tables.py")
    tex.append(r"\begin{table}[t]")
    tex.append(r"\centering")
    tex.append(r"\caption{Attention Workload: Software-Only vs "
               r"Hardware Coprocessor}")
    tex.append(r"\label{tab:cycle-comparison}")
    tex.append(r"\begin{tabular}{lrrrr}")
    tex.append(r"\toprule")
    tex.append(r"\textbf{Format} & \textbf{SW Cycles} & "
               r"\textbf{HW Cycles} & \textbf{Speedup} & "
               r"\textbf{Binary} \\")
    tex.append(r"\midrule")

    for fmt in FORMATS:
        label = FORMAT_LABELS.get(fmt, fmt)
        sw = SW_CYCLES.get(fmt, 0)
        hw = HW_CYCLES_EST.get(fmt, 0)
        bsz = BINARY_SIZES.get(fmt, 0)
        speedup = sw / hw if hw > 0 else 0
        tex.append(f"  {label} & {sw:,} & $\\sim${hw:,} & "
                   f"{speedup:.1f}$\\times$ & {bsz}\\,B \\\\")

    tex.append(r"\bottomrule")
    tex.append(r"\end{tabular}")
    tex.append(r"\end{table}")

    path = os.path.join(output_dir, "cycle_comparison.tex")
    with open(path, "w") as f:
        f.write("\n".join(tex) + "\n")
    print(f"  Saved {path}")


