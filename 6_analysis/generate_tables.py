# ─────────────────────────────────────────────────────────────────────
# Main
# ─────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(
        description="Generate LaTeX tables for MX fault analysis paper")
    parser.add_argument("results_dir", nargs="?", default=None,
                        help="Directory containing CSV results (optional)")
    parser.add_argument("--output", default=None,
                        help="Output directory for .tex files")
    args = parser.parse_args()

    if args.output:
        output_dir = args.output
    elif args.results_dir:
        output_dir = os.path.join(args.results_dir, "tables")
    else:
        output_dir = "tables"

    os.makedirs(output_dir, exist_ok=True)

    # Load SRAM results if available
    all_data = {}
    if args.results_dir and os.path.isdir(args.results_dir):
        print("Loading SRAM fault results...")
        all_data = load_results(args.results_dir)

    # Generate tables (some are data-dependent, some are static)
    print("\nGenerating LaTeX tables...")

    if all_data:
        gen_vulnerability_ranking(all_data, output_dir)
        gen_per_matrix_breakdown(all_data, output_dir)
        gen_bit_sensitivity(all_data, output_dir)
        gen_comparison_table(all_data, output_dir)
    else:
        print("  (No SRAM results — skipping data-dependent tables)")

    # Static tables (always generated)
    gen_cycle_comparison(output_dir)
    gen_resource_utilization(output_dir)
    gen_instruction_encoding(output_dir)
    gen_scan_chain_map(output_dir)

    print(f"\nAll tables saved to {output_dir}")


if __name__ == "__main__":
    main()
